#!/usr/bin/env python3
"""
Build js/childcare.js: licensed child care centres located in Toronto elementary school buildings.

Source: City of Toronto Open Data, "Licensed Child Care Centres" (updated daily; Open Government Licence - Toronto).
Each centre in a school building ("Public/Catholic Elementary School", "Public Middle School") is matched to
the nearest elementary school in js/schools-ontario.js whose name agrees with the building name, so TDSB,
Toronto Catholic and French-language schools are all covered.

Usage:
    python3 tools/fetch_childcare.py
"""
import csv
import io
import json
import math
import os
import re
import unicodedata
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKAGE = "https://ckan0.cf.opendata.inter.prod-toronto.ca/api/3/action/package_show?id=licensed-child-care-centres"
DATASET = "https://open.toronto.ca/dataset/licensed-child-care-centres/"
UA = {"User-Agent": "tdsb-curriculum-guide (parent education site)"}
SCHOOL_BLDG = {"Public Elementary School", "Catholic Elementary School", "Public Middle School"}
GENERIC = {"school", "public", "junior", "senior", "middle", "and", "the", "of", "elementary", "catholic", "jr", "sr",
           "ps", "academy", "community", "st", "saint", "ecole", "elementaire", "catholique"}


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=120) as r:
        return r.read()


def words(name):
    s = unicodedata.normalize("NFD", name or "").encode("ascii", "ignore").decode().lower()
    return {w.rstrip("s") for w in re.findall(r"[a-z]+", s)} - {w.rstrip("s") for w in GENERIC}  # "Roseland(s)", "St Clement(s)"


def km(a, b):
    dx = (a[1] - b[1]) * 111.32 * math.cos(math.radians(a[0]))
    return math.hypot(dx, (a[0] - b[0]) * 110.57)


def num(v):
    try:
        return int(float(v))
    except (TypeError, ValueError):
        return 0


def main():
    pkg = json.loads(fetch(PACKAGE))["result"]
    url = next(r["url"] for r in pkg["resources"] if r["format"].upper() == "CSV")
    rows = list(csv.DictReader(io.StringIO(fetch(url).decode("utf-8-sig"))))
    print(f"child care centres: {len(rows)}")

    with open(os.path.join(ROOT, "js", "schools-ontario.js"), encoding="utf-8") as f:
        O = json.loads(re.search(r"window\.SCHOOLS_ON\s*=\s*(\{.*\});\s*$", f.read(), re.S).group(1))
    schools = [(r[0], r[1], (r[5], r[6])) for r in O["rows"] if r[5] is not None]

    out, unmatched, run_date = {}, [], ""
    for r in rows:
        if r.get("bldg_type") not in SCHOOL_BLDG:
            continue
        run_date = r.get("run_date") or run_date
        try:
            lon, lat = json.loads(r["geometry"])["coordinates"][0]
        except (ValueError, KeyError, IndexError, TypeError):
            continue
        bw = words(r.get("BLDGNAME"))
        near = sorted(((km((lat, lon), xy), sid, name) for sid, name, xy in schools if km((lat, lon), xy) < 2.0))
        # nearest school sharing a distinctive name word; by distance alone only when the building name says nothing
        pick = next((x for x in near if bw & words(x[2])), None)
        if not pick and not bw and near and near[0][0] < 0.12:
            pick = near[0]
        if not pick and bw:  # map coordinates disagree: accept a unique exact name match anywhere in Toronto
            same = [(0, sid, name) for sid, name, xy in schools if words(name) == bw and km((lat, lon), xy) < 25]
            pick = same[0] if len(same) == 1 else None
        if not pick:
            unmatched.append(f"{r.get('BLDGNAME')} ({r.get('LOC_NAME')})")
            continue
        out.setdefault(pick[1], []).append({
            "n": r["LOC_NAME"].strip(),
            "a": {"Non Profit Agency": "np", "Commercial Agency": "com", "Public (City Operated) Agency": "city"}.get(r.get("AUSPICE"), ""),
            "sp": [num(r.get(k)) for k in ("IGSPACE", "TGSPACE", "PGSPACE", "KGSPACE", "SGSPACE")],  # infant, toddler, preschool, kindergarten, school-age
            "sub": r.get("subsidy") == "Y", "cw": r.get("cwelcc_flag") == "Y", "ph": r.get("PHONE", "").strip()})
    print(f"matched {sum(len(v) for v in out.values())} centres to {len(out)} schools; unmatched {len(unmatched)}: {unmatched[:15]}")

    dest = os.path.join(ROOT, "js", "childcare.js")
    with open(dest, "w", encoding="utf-8") as f:
        f.write("/* Licensed child care centres in Toronto elementary school buildings. Source: City of Toronto Open Data,\n"
                "   Licensed Child Care Centres (Open Government Licence - Toronto). Generated by tools/fetch_childcare.py -- do not edit by hand. */\n")
        f.write("window.CHILDCARE = ")
        # no run date: it changes daily and would make every monthly refresh look like a data change
        json.dump({"source": DATASET, "schools": out}, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print(f"wrote {dest} ({os.path.getsize(dest) // 1024} KB)")


if __name__ == "__main__":
    main()
